import hashlib, io, json, os, pathlib, platform, stat, subprocess, sys, unittest
if __name__ == '__main__':
    expected_head = os.environ['EXPECTED_HEAD']
    git_executable = pathlib.Path('C:/Program Files/Git/cmd/git.exe' if os.name=='nt' else '/usr/bin/git').resolve(strict=True)
    assert git_executable.is_file() and not git_executable.is_relative_to(pathlib.Path.cwd().resolve(strict=True)), 'unadmitted Git bootstrap executable'
    source_git = [str(git_executable), '--no-replace-objects', '--no-optional-locks', '-c', 'core.fsmonitor=false']
    source_objects = {}
    for entry in subprocess.check_output([*source_git,'ls-tree','-r','-z',expected_head]).split(b'\0'):
        if not entry: continue
        metadata, name = entry.split(b'\t',1)
        source_objects[name.decode('utf-8')] = metadata.split()[2].decode('ascii')
    source_paths = tuple(source_objects)
    def git(*args):
        return subprocess.check_output([*source_git, *args], timeout=15)
    def source_receipt():
        head = git('rev-parse', 'HEAD').decode().strip()
        assert head == expected_head, 'unexpected source head'
        tree = git('rev-parse', 'HEAD^{tree}').decode().strip()
        assert tree == git('rev-parse', expected_head + '^{tree}').decode().strip()
        assert not git('status', '--porcelain', '--untracked-files=no', '--ignore-submodules=none').strip(), 'tracked source dirty'
        files = {}
        for name in source_paths:
            path = pathlib.Path(name)
            current = pathlib.Path('.')
            for part in path.parts:
                current = current / part
                metadata = current.lstat()
                assert not stat.S_ISLNK(metadata.st_mode)
                assert not getattr(metadata, 'st_file_attributes', 0) & getattr(stat, 'FILE_ATTRIBUTE_REPARSE_POINT', 1024)
            assert path.is_file(), 'nonregular source input'
            raw = path.read_bytes()
            blob = git('cat-file', 'blob', source_objects[name])
            assert raw == blob, 'raw source differs from committed blob: ' + name
            files[name] = dict(bytes=len(raw), raw_sha256=hashlib.sha256(raw).hexdigest(),
                blob_sha256=hashlib.sha256(blob).hexdigest(),
                git_blob=source_objects[name])
        return dict(head=head, tree=tree, files=files, tracked_clean=True,
            object_resolution='PRIMARY_GIT_OBJECTS_NO_REPLACE')
    def require_source_only_imports(after_tests=False):
        assert sys.flags.isolated, 'fresh isolated interpreter required'
        assert sys.pycache_prefix is None, 'redirected bytecode cache is not admitted'
        root = pathlib.Path.cwd().resolve(strict=True)
        for candidate in root.rglob('*'):
            relative = candidate.relative_to(root)
            if '.git' in relative.parts: continue
            assert candidate.suffix.lower() not in ('.pyc','.pyo'), 'preexisting or generated bytecode rejected'
            if candidate.is_file() or candidate.is_symlink():
                allowed_output = after_tests and relative.as_posix()=='partial-integration-ci-tests.log'
                assert relative.as_posix() in source_objects or allowed_output, 'unexpected repository file rejected: ' + relative.as_posix()
    require_source_only_imports()
    before = source_receipt()
    sys.path.insert(0, str(pathlib.Path.cwd().resolve(strict=True)))
    inventory=json.loads(pathlib.Path('release/component-test-inventory.json').read_bytes())
    suite=unittest.TestSuite(unittest.defaultTestLoader.loadTestsFromName(name) for name in inventory['modules'])
    def cases(value):
        for item in value:
            if isinstance(item, unittest.TestSuite): yield from cases(item)
            else: yield item
    test_ids=[case.id() for case in cases(suite)]
    assert inventory['schema']=='unified.integration-component-tests.v5'
    assert inventory['expected_count']==145
    assert len(test_ids)==len(set(test_ids))==145
    assert len(inventory['preserved_prior_ids'])==144
    assert set(inventory['preserved_prior_ids'])<=set(test_ids), 'prior mandatory cases removed'
    assert sorted(test_ids)==inventory['expected_test_ids'], 'mandatory test inventory differs'
    stream = io.StringIO()
    result = unittest.TextTestRunner(stream=stream, verbosity=2).run(suite)
    log = stream.getvalue().encode('utf-8')
    pathlib.Path('partial-integration-ci-tests.log').write_bytes(log)
    print(stream.getvalue(), end='')
    require_source_only_imports(after_tests=True)
    after = source_receipt()
    assert before == after, 'source changed during tests'
    report = dict(schema='unified.partial-integration.ci.v2', head=before['head'], tree=before['tree'],
        source_before=before, source_after=after, mandatory_test_ids=test_ids,
        test_log_sha256=hashlib.sha256(log).hexdigest(), source_binding_passed=True,
        os=platform.system(), python=platform.python_version(), tests=result.testsRun,
        failures=len(result.failures), errors=len(result.errors), skipped=len(result.skipped),
        run=os.environ['GITHUB_RUN_ID'], attempt=os.environ['GITHUB_RUN_ATTEMPT'],
        qualification='PARTIAL_INTEGRATION_COMPONENTS_ONLY_SOURCE_CHECKED_BEFORE_AFTER',
        product_import_policy='ISOLATED_REJECT_REPO_BYTECODE_UNEXPECTED_PY_AND_CACHE_REDIRECT_PRE_POST',
        bootstrap_git_path=str(git_executable), bootstrap_git_raw_sha256=hashlib.sha256(git_executable.read_bytes()).hexdigest(),
        run_metadata='CORRELATION_ONLY_NOT_HOSTED_ATTESTATION',
        runtime_api='NOT_QUALIFIED', physical='NOT_RUN', production='NO_GO')
    pathlib.Path('partial-integration-ci-evidence.json').write_text(json.dumps(report, indent=2), encoding='utf-8')
    assert result.wasSuccessful() and result.testsRun == 145 and not result.skipped
